"""
OMS Project - Stage 4: Candidate Intent Lifecycle & Controlled Market Adaptability
(candidate_intent.py)

Implements:
1. Candidate Intent Lifecycle:
   - CandidateIntent: Data contract for strategy-proposed trades (distinct from direct orders).
   - CandidateIntentState: CANDIDATE -> RISK_APPROVED -> SIZED -> DISPATCHED (or REJECTED_BY_REGIME / REJECTED_BY_RISK).
   - Explicit audit trail recording all state transitions with timestamps, rationales, and metadata.
2. Market Adaptation Profiles & Transition Management:
   - MarketAdaptationProfile: TRENDING, CHOPPY, HIGH_VOLATILITY, LOW_LIQUIDITY, DEGRADED_DATA, NORMAL.
   - ProfileTransitionManager: Dynamic transitions with confirmation threshold and hysteresis cooldown.
   - Fail-closed controls: DEGRADED_DATA strictly forces NO_TRADE for entries; allows REDUCE_ONLY.
3. Decision Engine & Risk Sizing Integration:
   - Stage4DecisionEngine: Gates candidate intents against active market regime and risk boundaries.
   - Regime-adaptive sizing: Volatility scaling, liquidity capping, and exposure verification.
   - Dispatch to Stage 3 PaperExchange / BrokerGateway with cryptographic signatures.
"""

from __future__ import annotations
import time
import uuid
import hmac
import hashlib
from enum import Enum
from typing import Dict, Any, Optional, List, Tuple
from pydantic import BaseModel, Field, field_validator

from oms_project.schemas import OrderIntent, OrderSide, OrderState, OrderType
from oms_project.deterministic_replay import MarketRegime, RegimeEvaluator, ReplayClock
from oms_project.paper_exchange import PaperExchange
from oms_project.gateway import BrokerGateway


class CandidateIntentState(str, Enum):
    CANDIDATE = "CANDIDATE"
    RISK_APPROVED = "RISK_APPROVED"
    SIZED = "SIZED"
    DISPATCHED = "DISPATCHED"
    REJECTED_BY_REGIME = "REJECTED_BY_REGIME"
    REJECTED_BY_RISK = "REJECTED_BY_RISK"


class IntentType(str, Enum):
    ENTRY_LONG = "ENTRY_LONG"
    ENTRY_SHORT = "ENTRY_SHORT"
    EXIT_LONG = "EXIT_LONG"
    EXIT_SHORT = "EXIT_SHORT"
    REDUCE_LONG = "REDUCE_LONG"
    REDUCE_SHORT = "REDUCE_SHORT"

    @property
    def is_reduce_only(self) -> bool:
        return self in (
            IntentType.EXIT_LONG,
            IntentType.EXIT_SHORT,
            IntentType.REDUCE_LONG,
            IntentType.REDUCE_SHORT,
        )

    @property
    def order_side(self) -> OrderSide:
        if self in (IntentType.ENTRY_LONG, IntentType.EXIT_SHORT, IntentType.REDUCE_SHORT):
            return OrderSide.BUY
        return OrderSide.SELL


class MarketAdaptationProfile(str, Enum):
    TRENDING = "TRENDING"
    CHOPPY = "CHOPPY"
    HIGH_VOLATILITY = "HIGH_VOLATILITY"
    LOW_LIQUIDITY = "LOW_LIQUIDITY"
    DEGRADED_DATA = "DEGRADED_DATA"
    NORMAL = "NORMAL"


class CandidateIntentTransitionError(Exception):
    """Raised when an illegal candidate intent state transition is attempted."""
    pass


class CandidateIntent(BaseModel):
    """
    Candidate Intent data contract generated by strategies.
    Strategies never emit direct broker orders; they emit CandidateIntent.
    """
    intent_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    strategy_id: str
    symbol: str
    intent_type: IntentType
    target_exposure: float = Field(..., gt=0, description="Target requested exposure (quantity or currency units)")
    time_horizon: str = Field(default="INTRADAY", description="Time horizon: INTRADAY, SCALP, SWING")
    max_slippage: float = Field(default=0.002, description="Max acceptable slippage as a fraction (e.g. 0.002 = 20 bps)")
    rationale: List[str] = Field(default_factory=list)
    regime_compatibility: List[str] = Field(
        default_factory=list,
        description="List of compatible MarketAdaptationProfile or MarketRegime names"
    )
    reference_price: float = Field(default=0.0, ge=0)
    stop_loss: Optional[float] = None
    target: Optional[float] = None
    reduce_only: bool = Field(default=False)
    created_at: float = Field(default_factory=time.time)
    state: CandidateIntentState = Field(default=CandidateIntentState.CANDIDATE)
    sized_qty: float = Field(default=0.0, ge=0)
    rejection_reason: Optional[str] = None
    dispatched_order_id: Optional[str] = None
    audit_trail: List[Dict[str, Any]] = Field(default_factory=list)

    @field_validator("symbol")
    @classmethod
    def validate_symbol(cls, v: str) -> str:
        s = v.strip().upper()
        if not s:
            raise ValueError("Symbol cannot be empty")
        return s

    def model_post_init(self, __context: Any) -> None:
        if not self.audit_trail:
            self.audit_trail.append({
                "from_state": None,
                "to_state": CandidateIntentState.CANDIDATE.value,
                "reason": "Created by strategy",
                "timestamp": self.created_at,
                "metadata": {
                    "strategy_id": self.strategy_id,
                    "symbol": self.symbol,
                    "target_exposure": self.target_exposure,
                },
            })
        if self.intent_type.is_reduce_only:
            self.reduce_only = True

    def transition(
        self,
        new_state: CandidateIntentState,
        reason: str,
        metadata: Optional[Dict[str, Any]] = None,
    ) -> None:
        """
        Executes a legal state transition and records an immutable audit record.
        Legal paths:
        CANDIDATE -> RISK_APPROVED, REJECTED_BY_REGIME, REJECTED_BY_RISK
        RISK_APPROVED -> SIZED, REJECTED_BY_RISK
        SIZED -> DISPATCHED, REJECTED_BY_RISK
        """
        valid_transitions = {
            CandidateIntentState.CANDIDATE: {
                CandidateIntentState.RISK_APPROVED,
                CandidateIntentState.REJECTED_BY_REGIME,
                CandidateIntentState.REJECTED_BY_RISK,
            },
            CandidateIntentState.RISK_APPROVED: {
                CandidateIntentState.SIZED,
                CandidateIntentState.REJECTED_BY_RISK,
            },
            CandidateIntentState.SIZED: {
                CandidateIntentState.DISPATCHED,
                CandidateIntentState.REJECTED_BY_RISK,
            },
            CandidateIntentState.DISPATCHED: set(),
            CandidateIntentState.REJECTED_BY_REGIME: set(),
            CandidateIntentState.REJECTED_BY_RISK: set(),
        }

        if new_state not in valid_transitions.get(self.state, set()):
            raise CandidateIntentTransitionError(
                f"Illegal candidate intent state transition from {self.state} to {new_state}"
            )

        old_state = self.state
        self.state = new_state
        if new_state in (CandidateIntentState.REJECTED_BY_REGIME, CandidateIntentState.REJECTED_BY_RISK):
            self.rejection_reason = reason

        self.audit_trail.append({
            "from_state": old_state.value,
            "to_state": new_state.value,
            "reason": reason,
            "timestamp": time.time(),
            "metadata": metadata or {},
        })


class ProfileTransitionManager:
    """
    Manages transitions between Market Adaptation Profiles.
    Implements:
    - Confirmation threshold (consecutive proposals) to prevent whipsawing.
    - Hysteresis cooldown on de-escalation from adverse/volatile regimes.
    - Instant fail-closed escalation for critical regimes (DEGRADED_DATA, HIGH_VOLATILITY).
    """

    def __init__(
        self,
        initial_profile: MarketAdaptationProfile = MarketAdaptationProfile.NORMAL,
        cooldown_seconds: float = 60.0,
        confirmation_threshold: int = 3,
    ):
        self._current_profile = initial_profile
        self.cooldown_seconds = cooldown_seconds
        self.confirmation_threshold = confirmation_threshold
        self._last_transition_time: float = 0.0
        self._pending_profile: Optional[MarketAdaptationProfile] = None
        self._pending_count: int = 0
        self._history: List[Dict[str, Any]] = [{
            "profile": initial_profile.value,
            "timestamp": time.time(),
            "reason": "INITIAL_PROFILE",
        }]

    @property
    def current_profile(self) -> MarketAdaptationProfile:
        return self._current_profile

    @property
    def history(self) -> List[Dict[str, Any]]:
        return list(self._history)

    def propose_profile(
        self,
        proposed_profile: MarketAdaptationProfile,
        timestamp: Optional[float] = None,
    ) -> Tuple[MarketAdaptationProfile, bool]:
        """
        Processes a newly observed profile candidate.
        Returns: (active_profile, did_transition)
        """
        ts = timestamp if timestamp is not None else time.time()

        if proposed_profile == self._current_profile:
            self._pending_profile = None
            self._pending_count = 0
            return self._current_profile, False

        # 1. EMERGENCY / SAFETY ESCALATION:
        # Immediate transition into DEGRADED_DATA or HIGH_VOLATILITY (zero delay/cooldown)
        is_emergency = proposed_profile in (
            MarketAdaptationProfile.DEGRADED_DATA,
            MarketAdaptationProfile.HIGH_VOLATILITY,
        )

        if is_emergency:
            old = self._current_profile
            self._current_profile = proposed_profile
            self._last_transition_time = ts
            self._pending_profile = None
            self._pending_count = 0
            self._history.append({
                "from_profile": old.value,
                "profile": proposed_profile.value,
                "timestamp": ts,
                "reason": "EMERGENCY_FAIL_CLOSED_ESCALATION",
            })
            return self._current_profile, True

        # 2. HYSTERESIS COOLDOWN CHECK:
        # If currently in DEGRADED_DATA or HIGH_VOLATILITY, cannot de-escalate until cooldown expires
        in_defensive_state = self._current_profile in (
            MarketAdaptationProfile.DEGRADED_DATA,
            MarketAdaptationProfile.HIGH_VOLATILITY,
        )
        if in_defensive_state and (ts - self._last_transition_time) < self.cooldown_seconds:
            # Still in cooldown; suppress de-escalation
            self._pending_profile = None
            self._pending_count = 0
            return self._current_profile, False

        # 3. CONFIRMATION THRESHOLD CHECK:
        # Normal transitions require multiple consecutive observations
        if self._pending_profile == proposed_profile:
            self._pending_count += 1
        else:
            self._pending_profile = proposed_profile
            self._pending_count = 1

        if self._pending_count >= self.confirmation_threshold:
            old = self._current_profile
            self._current_profile = proposed_profile
            self._last_transition_time = ts
            self._pending_profile = None
            self._pending_count = 0
            self._history.append({
                "from_profile": old.value,
                "profile": proposed_profile.value,
                "timestamp": ts,
                "reason": f"CONFIRMED_AFTER_{self.confirmation_threshold}_OBSERVATIONS",
            })
            return self._current_profile, True

        return self._current_profile, False


def map_market_regime_to_profile(regime: MarketRegime) -> MarketAdaptationProfile:
    """
    Maps Stage 2 MarketRegime to Stage 4 MarketAdaptationProfile.
    """
    if regime in (MarketRegime.BULLISH_TREND, MarketRegime.BEARISH_TREND):
        return MarketAdaptationProfile.TRENDING
    elif regime in (MarketRegime.RANGE_BOUND, MarketRegime.LOW_VOLATILITY):
        return MarketAdaptationProfile.CHOPPY
    elif regime in (MarketRegime.HIGH_VOLATILITY, MarketRegime.OPENING_CLOSING_VOLATILITY):
        return MarketAdaptationProfile.HIGH_VOLATILITY
    elif regime == MarketRegime.LOW_LIQUIDITY:
        return MarketAdaptationProfile.LOW_LIQUIDITY
    elif regime in (MarketRegime.DEGRADED_DATA, MarketRegime.UNCERTAIN):
        return MarketAdaptationProfile.DEGRADED_DATA
    return MarketAdaptationProfile.NORMAL


class Stage4DecisionEngine:
    """
    Controlled Market Adaptability Decision Engine.
    Executes the Candidate Intent Lifecycle:
    Strategy -> CandidateIntent -> Regime Gating -> Risk Sizing -> Dispatched Order.
    """

    def __init__(
        self,
        transition_manager: Optional[ProfileTransitionManager] = None,
        regime_evaluator: Optional[RegimeEvaluator] = None,
        paper_exchange: Optional[PaperExchange] = None,
        gateway: Optional[BrokerGateway] = None,
        max_capital_per_trade: float = 50000.0,
        max_portfolio_exposure: float = 200000.0,
        volatility_sizing_scalar: float = 0.5,
        low_liquidity_cap_qty: float = 25.0,
        signing_secret: str = "pod_secret_stage4",
    ):
        self.transition_manager = transition_manager or ProfileTransitionManager()
        self.regime_evaluator = regime_evaluator or RegimeEvaluator()
        self.paper_exchange = paper_exchange
        self.gateway = gateway
        self.max_capital_per_trade = max_capital_per_trade
        self.max_portfolio_exposure = max_portfolio_exposure
        self.volatility_sizing_scalar = volatility_sizing_scalar
        self.low_liquidity_cap_qty = low_liquidity_cap_qty
        self.signing_secret = signing_secret
        self.processed_intents: List[CandidateIntent] = []

    @property
    def active_profile(self) -> MarketAdaptationProfile:
        return self.transition_manager.current_profile

    def update_market_regime(
        self,
        clock: ReplayClock,
        history: List[Dict[str, Any]],
        current_tick: Dict[str, Any],
    ) -> Tuple[MarketAdaptationProfile, MarketRegime]:
        """
        Evaluates Stage 2 RegimeEvaluator and updates Market Adaptation Profile with hysteresis.
        """
        regime, conf = self.regime_evaluator.evaluate(clock, history, current_tick)
        profile = map_market_regime_to_profile(regime)
        self.transition_manager.propose_profile(profile, clock.current_time)
        return self.transition_manager.current_profile, regime

    def process_candidate_intent(
        self,
        intent: CandidateIntent,
        current_price: float,
        portfolio_positions: Optional[Dict[str, float]] = None,
        available_cash: float = 100000.0,
        current_time: Optional[float] = None,
        dispatch_immediately: bool = True,
    ) -> CandidateIntent:
        """
        Processes a CandidateIntent through the 4-phase lifecycle:
        1. CANDIDATE -> Regime Gating -> RISK_APPROVED or REJECTED_BY_REGIME
        2. RISK_APPROVED -> Dynamic Risk Sizing -> SIZED or REJECTED_BY_RISK
        3. SIZED -> Execution Dispatch -> DISPATCHED (if dispatch_immediately is True)
        """
        self.processed_intents.append(intent)
        ts = current_time if current_time is not None else time.time()
        positions = portfolio_positions or {}
        active_prof = self.active_profile

        # -------------------------------------------------------------
        # PHASE 1: REGIME GATING & FAIL-CLOSED CHECKS
        # -------------------------------------------------------------
        # Fail-closed invariant: DEGRADED_DATA regime mandates NO_TRADE or REDUCE_ONLY
        if active_prof == MarketAdaptationProfile.DEGRADED_DATA:
            if not intent.reduce_only and not intent.intent_type.is_reduce_only:
                intent.transition(
                    CandidateIntentState.REJECTED_BY_REGIME,
                    "FAIL_CLOSED: DEGRADED_DATA regime mandates NO_TRADE for new entries",
                    {"active_profile": active_prof.value},
                )
                return intent

        # Strategy Regime Compatibility Check
        if intent.regime_compatibility:
            compatible = any(
                comp.upper() in (active_prof.value, active_prof.name)
                for comp in intent.regime_compatibility
            )
            # Check if reduce-only overrides regime incompatibility
            if not compatible and not (intent.reduce_only or intent.intent_type.is_reduce_only):
                intent.transition(
                    CandidateIntentState.REJECTED_BY_REGIME,
                    f"STRATEGY_INCOMPATIBLE: Strategy not compatible with active regime {active_prof.value}",
                    {
                        "active_profile": active_prof.value,
                        "compatible_profiles": intent.regime_compatibility,
                    },
                )
                return intent

        # Candidate passed regime gating!
        intent.transition(
            CandidateIntentState.RISK_APPROVED,
            f"Approved by regime gate under {active_prof.value}",
            {"active_profile": active_prof.value},
        )

        # -------------------------------------------------------------
        # PHASE 2: RISK CHECK & DYNAMIC MARKET ADAPTABILITY SIZING
        # -------------------------------------------------------------
        # Base requested quantity calculation:
        # If target_exposure <= 1000, treat directly as shares/contracts; else currency exposure
        if intent.target_exposure > 1000.0 and current_price > 0:
            base_qty = intent.target_exposure / current_price
        else:
            base_qty = intent.target_exposure

        # Dynamic Sizing Adaptations:
        if active_prof == MarketAdaptationProfile.HIGH_VOLATILITY:
            # Scale down size under high volatility to contain drawdowns
            effective_qty = base_qty * self.volatility_sizing_scalar
            sizing_reason = f"Volatility-scaled by {self.volatility_sizing_scalar:.2f} under HIGH_VOLATILITY"
        elif active_prof == MarketAdaptationProfile.LOW_LIQUIDITY:
            # Cap size under low liquidity to avoid outsized market impact
            effective_qty = min(base_qty, self.low_liquidity_cap_qty)
            sizing_reason = f"Liquidity-capped to max {self.low_liquidity_cap_qty:.1f} units under LOW_LIQUIDITY"
        else:
            effective_qty = base_qty
            sizing_reason = f"Standard full sizing under {active_prof.value}"

        # Reduce-only clamp: cannot exceed existing opposite position
        if intent.reduce_only or intent.intent_type.is_reduce_only:
            current_pos = positions.get(intent.symbol, 0.0)
            if intent.intent_type in (IntentType.EXIT_LONG, IntentType.REDUCE_LONG):
                if current_pos <= 0:
                    intent.transition(
                        CandidateIntentState.REJECTED_BY_RISK,
                        "REDUCE_ONLY_REJECTED: No long position exists to reduce",
                        {"current_position": current_pos},
                    )
                    return intent
                effective_qty = min(effective_qty, current_pos)
            elif intent.intent_type in (IntentType.EXIT_SHORT, IntentType.REDUCE_SHORT):
                if current_pos >= 0:
                    intent.transition(
                        CandidateIntentState.REJECTED_BY_RISK,
                        "REDUCE_ONLY_REJECTED: No short position exists to reduce",
                        {"current_position": current_pos},
                    )
                    return intent
                effective_qty = min(effective_qty, abs(current_pos))

        # Risk exposure limit checks:
        order_value = effective_qty * current_price
        if not (intent.reduce_only or intent.intent_type.is_reduce_only):
            # Check single-trade capital cap
            if order_value > self.max_capital_per_trade:
                intent.transition(
                    CandidateIntentState.REJECTED_BY_RISK,
                    f"CAPITAL_LIMIT_EXCEEDED: Trade value {order_value:.2f} exceeds max {self.max_capital_per_trade:.2f}",
                    {"order_value": order_value, "max_capital": self.max_capital_per_trade},
                )
                return intent

            # Check cash solvency
            if order_value > available_cash:
                intent.transition(
                    CandidateIntentState.REJECTED_BY_RISK,
                    f"INSUFFICIENT_CASH: Required {order_value:.2f} exceeds available {available_cash:.2f}",
                    {"required_cash": order_value, "available_cash": available_cash},
                )
                return intent

            # Check overall portfolio exposure
            current_gross_exposure = sum(abs(q) * current_price for q in positions.values())
            if (current_gross_exposure + order_value) > self.max_portfolio_exposure:
                intent.transition(
                    CandidateIntentState.REJECTED_BY_RISK,
                    f"PORTFOLIO_EXPOSURE_EXCEEDED: Total exposure {current_gross_exposure + order_value:.2f} exceeds max {self.max_portfolio_exposure:.2f}",
                    {"total_exposure": current_gross_exposure + order_value},
                )
                return intent

        intent.sized_qty = round(effective_qty, 4)
        intent.transition(
            CandidateIntentState.SIZED,
            sizing_reason,
            {"sized_qty": intent.sized_qty, "price": current_price, "order_value": order_value},
        )

        # -------------------------------------------------------------
        # PHASE 3: EXECUTION DISPATCH
        # -------------------------------------------------------------
        if dispatch_immediately:
            self._dispatch_intent(intent, current_price, ts)
        return intent

    def _sign_intent_payload(
        self,
        req_id: str,
        strategy_id: str,
        symbol: str,
        side: str,
        qty: float,
        price: float,
        timestamp: float,
    ) -> str:
        payload = f"{req_id}:{strategy_id}:{symbol}:{side}:{qty}:{price}:{timestamp}"
        return hmac.new(self.signing_secret.encode(), payload.encode(), hashlib.sha256).hexdigest()

    def _dispatch_intent(self, intent: CandidateIntent, current_price: float, timestamp: float) -> None:
        """
        Translates a SIZED CandidateIntent into an executable OrderIntent and submits
        to PaperExchange or BrokerGateway.
        """
        req_id = f"REQ_ST4_{intent.intent_id[:8]}"
        side = intent.intent_type.order_side
        signature = self._sign_intent_payload(
            req_id,
            intent.strategy_id,
            intent.symbol,
            side.value,
            intent.sized_qty,
            current_price,
            timestamp,
        )

        # 1. Dispatch to PaperExchange if configured
        if self.paper_exchange is not None:
            exec_res = self.paper_exchange.execute_order(
                strategy_id=intent.strategy_id,
                symbol=intent.symbol,
                side=side.value,
                qty=intent.sized_qty,
                price=current_price,
                signing_token=f"v1.signing.{signature}",
                broker_order_id=f"BKR_{req_id}",
                order_type="MARKET",
                reduce_only=intent.reduce_only,
            )
            dispatched_id = exec_res.get("broker_order_id", f"BKR_{req_id}")
            intent.dispatched_order_id = dispatched_id
            intent.transition(
                CandidateIntentState.DISPATCHED,
                "Dispatched to internal PaperExchange",
                {"broker_order_id": dispatched_id, "execution_result": exec_res},
            )
            return

        # 2. Dispatch to BrokerGateway if configured
        if self.gateway is not None:
            order_intent = OrderIntent(
                request_id=req_id,
                strategy_id=intent.strategy_id,
                symbol=intent.symbol,
                side=side,
                qty=intent.sized_qty,
                price=current_price,
                order_type=OrderType.MARKET,
                reduce_only=intent.reduce_only,
                timestamp=timestamp,
                signature=signature,
            )
            res = self.gateway.process_order_intent(order_intent)
            intent.dispatched_order_id = res.order_id
            intent.transition(
                CandidateIntentState.DISPATCHED,
                "Dispatched to BrokerGateway",
                {"order_id": res.order_id, "order_status": res.status.value},
            )
            return

        # 3. Simulated standalone dispatch if no exchange hooked up
        dispatched_id = f"DISPATCH_SIM_{req_id}"
        intent.dispatched_order_id = dispatched_id
        intent.transition(
            CandidateIntentState.DISPATCHED,
            "Dispatched in standalone simulation mode",
            {"dispatched_id": dispatched_id},
        )
